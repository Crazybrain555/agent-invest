def _scalar(value: object) -> str:
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if type(value) is int:
        return str(value)
    if type(value) is str:
        if "\n" in value:
            raise ValueError("multi-line strings must be emitted as literal blocks")
        return json.dumps(value, ensure_ascii=False)
    raise ValueError(f"unsupported Compose scalar type: {type(value).__name__}")


def _key(value: object) -> str:
    if type(value) is not str or not value:
        raise ValueError("Compose mapping keys must be non-empty strings")
    return value if _PLAIN_KEY_RE.fullmatch(value) else json.dumps(value, ensure_ascii=False)


def _emit(value: object, indent: int, lines: list[str]) -> None:
    pad = " " * indent
    if type(value) is dict:
        if not value:
            raise ValueError("empty Compose mappings are not emitted")
        for key, item in value.items():
            if type(item) is dict and item:
                lines.append(f"{pad}{_key(key)}:")
                _emit(item, indent + 2, lines)
            elif type(item) is list and item:
                lines.append(f"{pad}{_key(key)}:")
                _emit(item, indent + 2, lines)
            elif type(item) is str and "\n" in item:
                lines.append(f"{pad}{_key(key)}: |")
                _emit_block(item, indent + 2, lines)
            else:
                lines.append(f"{pad}{_key(key)}: {_scalar(item)}")
        return
    if type(value) is list:
        if not value:
            raise ValueError("empty Compose lists are not emitted")
        for item in value:
            if type(item) is dict and item:
                first = True
                for key, nested in item.items():
                    prefix = f"{pad}- " if first else f"{pad}  "
                    first = False
                    if type(nested) is dict and nested:
                        lines.append(f"{prefix}{_key(key)}:")
                        _emit(nested, indent + 4, lines)
                    elif type(nested) is list and nested:
                        lines.append(f"{prefix}{_key(key)}:")
                        _emit(nested, indent + 4, lines)
                    elif type(nested) is str and "\n" in nested:
                        lines.append(f"{prefix}{_key(key)}: |")
                        _emit_block(nested, indent + 4, lines)
                    else:
                        lines.append(f"{prefix}{_key(key)}: {_scalar(nested)}")
            elif type(item) is list:
                raise ValueError("nested Compose lists are not emitted")
            elif type(item) is str and "\n" in item:
                lines.append(f"{pad}- |")
                _emit_block(item, indent + 2, lines)
            else:
                lines.append(f"{pad}- {_scalar(item)}")
        return
    raise ValueError("Compose root must be a mapping")


def _emit_block(text: str, indent: int, lines: list[str]) -> None:
    if not text.endswith("\n") or text.count("\n") != len(text.split("\n")) - 1 or "\r" in text:
        raise ValueError("literal block text must end with one newline and contain no carriage returns")
    body = text[:-1].split("\n")
    if body[0] and body[0][0] in " \t":
        raise ValueError("literal block must not start with indentation")
    if any(line != line.rstrip() for line in body):
        raise ValueError("literal block lines must not carry trailing whitespace")
    pad = " " * indent
    for line in body:
        lines.append(f"{pad}{line}" if line else "")


def render_compose_yaml(document: dict[str, Any]) -> bytes:
    lines: list[str] = []
    _emit(document, 0, lines)
    return (COMPOSE_HEADER + "\n".join(lines) + "\n").encode("utf-8")


class _UniqueKeyLoader(yaml.SafeLoader):
    pass


def _construct_unique_mapping(loader: yaml.SafeLoader, node: yaml.MappingNode) -> dict[Any, Any]:
    mapping: dict[Any, Any] = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=True)
        if key in mapping:
            raise ValueError(f"duplicate Compose key: {key!r}")
        mapping[key] = loader.construct_object(value_node, deep=True)
    return mapping


_UniqueKeyLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _construct_unique_mapping)


def parse_compose_yaml(payload: bytes) -> dict[str, Any]:
    if type(payload) is not bytes or not payload or len(payload) > 256 * 1024:
        raise ValueError("Compose bytes are outside the closed envelope")
    try:
        value = yaml.load(payload.decode("utf-8"), Loader=_UniqueKeyLoader)  # noqa: S506 - SafeLoader subclass
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise ValueError(f"Compose is not parseable YAML: {exc}") from exc
    if type(value) is not dict:
        raise ValueError("Compose root must be a mapping")
    return value


def verify_compose_projection(
    document: dict[str, Any], capacity: MineruCapacityConfig, profile: MineruDeploymentProfile,
) -> list[str]:
    """Return every mismatch between a parsed Compose and the exact projection."""

    mismatches: list[str] = []
    expected = compose_document(profile, capacity)
    if document != expected:
        api = document.get("services", {}).get("mineru-api") if type(document.get("services")) is dict else None
        environment = api.get("environment") if type(api) is dict else None
        if type(environment) is not dict:
            mismatches.append("services.mineru-api.environment: missing")
        else:
            for name, value in capacity_environment(capacity).items():
                if environment.get(name) != value:
                    mismatches.append(f"services.mineru-api.environment.{name}: {environment.get(name)!r} != {value!r}")
            for name in ("MINERU_CAPACITY_CONFIG_PATH", "MINERU_CAPACITY_CONFIG_SHA256"):
                if name in environment:
                    mismatches.append(f"services.mineru-api.environment.{name}: compose must not override the image anchor")
            extra = set(environment) - set(expected["services"]["mineru-api"]["environment"])
            for name in sorted(extra):
                mismatches.append(f"services.mineru-api.environment.{name}: undeclared variable")
        command = api.get("command") if type(api) is dict else None
        if command != list(api_command_argv(capacity)):
            mismatches.append(f"services.mineru-api.command: {command!r} != {list(api_command_argv(capacity))!r}")
        if not mismatches:
            mismatches.append("compose document differs from the exact projection outside capacity fields")
    return mismatches


def resolve_release(
    capacity: MineruCapacityConfig,
    deployment_profile: MineruDeploymentProfile,
    local_profile: MineruLocalWorkerProfile,
) -> ReleasePlan:
    """Project all inputs once; pure and deterministic."""

    require_current_runtime_capabilities(capacity)
    deployment_profile.__post_init__()
    local_profile.__post_init__()
    document = compose_document(deployment_profile, capacity)
    rendered = render_compose_yaml(document)
    if parse_compose_yaml(rendered) != document:
        raise ValueError("rendered Compose does not round-trip to its structured document")
    # The Mac process-profile contract requires every admitted pending task to
    # hold a full reservation within the retained-result budget; the API
    # registry itself only backpressures. Report the difference; never hide it.
    admits_full_pending = (
        capacity.result_reservation_bytes * capacity.total_nonterminal_limit <= capacity.max_unacked_result_bytes
    )
    return ReleasePlan(
        api_environment=capacity_environment(capacity),
        api_command=api_command_argv(capacity),
        compose_document=document,
        compose_bytes=rendered,
        local_profile_admits_full_pending=admits_full_pending,
    )


