"""Pure release projection: capacity + deployment profile -> complete Compose.

No network, Docker, database or filesystem access. The Compose document is a
structured object rendered by a deterministic emitter and re-parsed for
verification; the only capacity numbers it contains come from the shared
codec projection. Nothing here reads a previous package.
"""

