    def test_no_capacity_anchors_does_not_call_bootstrap_and_reports_none(self):
        with patch.dict(os.environ, {"MINERU_PHASE_TRACE": "1"}, clear=True):
            event = self.record(weak_wrapper(hybrid()))
        self.assertIsNone(event["capacity_config_sha256"])
        self.bootstrap.get_process_capacity.assert_not_called()

    def test_identity_uses_verified_getter_result_not_environment_echo(self):
        self.bootstrap.get_process_capacity.return_value = SimpleNamespace(
            sha256="sha256:" + "b" * 64
        )
        event = self.record(weak_wrapper(hybrid()))
        self.assertEqual(
            os.environ["MINERU_CAPACITY_CONFIG_SHA256"], "sha256:" + "a" * 64
        )
        self.assertEqual(event["capacity_config_sha256"], "sha256:" + "b" * 64)
        self.bootstrap.get_process_capacity.assert_called_once_with()

    def test_actual_bootstrap_verifies_file_and_rejects_later_capacity_environment_drift(
        self,
    ):
        with self.real_bootstrap() as (bootstrap, digest):
            verified = bootstrap.get_process_capacity()
            self.assertEqual(verified.sha256, digest)
            with patch.object(
                bootstrap, "get_process_capacity", wraps=bootstrap.get_process_capacity
            ) as getter:
                event = self.record(weak_wrapper(hybrid()))
                self.assertEqual(event["capacity_config_sha256"], digest)
                getter.assert_called_once_with()
            for key, bad in [
                ("OMP_NUM_THREADS", "99"),
                ("MINERU_CAPACITY_CONFIG_SHA256", "sha256:" + "0" * 64),
                ("MINERU_CAPACITY_CONFIG_PATH", "/not-the-bound-file"),
            ]:
                with self.subTest(key=key), patch.dict(os.environ, {key: bad}):
                    count = len(self.events())
                    item = weak_wrapper(hybrid())
                    with self.assertRaisesRegex(RuntimeError, "drifted"):
                        self.record(item)
                    self.assertEqual(len(self.events()), count)
                # A rejected record does not mark the serving object as seen.
                self.assertIsNotNone(self.record(item))

    def test_either_partial_capacity_anchor_invokes_actual_bootstrap_and_rejects(self):
        for remove in ("MINERU_CAPACITY_CONFIG_PATH", "MINERU_CAPACITY_CONFIG_SHA256"):
            with (
                self.subTest(remove=remove),
                self.real_bootstrap() as (bootstrap, _digest),
            ):
                del os.environ[remove]
                with patch.object(
                    bootstrap,
                    "get_process_capacity",
                    wraps=bootstrap.get_process_capacity,
                ) as getter:
                    with self.assertRaisesRegex(
                        ValueError, "path and SHA must both be explicit"
                    ):
                        self.record(weak_wrapper(hybrid()))
                    getter.assert_called_once_with()
        self.assertEqual(self.events(), [])

