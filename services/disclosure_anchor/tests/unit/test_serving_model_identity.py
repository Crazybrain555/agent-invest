    def test_actual_cpu_tensors_override_cuda_environment_and_wrapper_claim(self):
        item = weak_wrapper(hybrid("cpu"))
        event = self.record(item)
        self.assertEqual(event["schema"], "mineru-hybrid-model-device.v1")
        self.assertEqual(event["observation"], "serving_instance_initialization")
        self.assertEqual(event["process_start_ticks"], 987654)
        self.assertEqual(event["process_id"], os.getpid())
        self.assertEqual(event["capacity_config_sha256"], "sha256:" + "a" * 64)
        self.assertEqual(event["instance_id"], id(item))
        self.assertEqual(
            set(event["models"]), {"layout", "mfr", "ocr_detector", "ocr_recognizer"}
        )
        for model in event["models"].values():
            self.assertEqual(model["state"], "available")
            self.assertEqual({g["device"] for g in model["tensor_groups"]}, {"cpu"})
            self.assertEqual(
                {g["dtype"] for g in model["tensor_groups"]}, {"torch.float32"}
            )
        self.assertEqual(self.events(), [event])

    def test_all_tensor_groups_include_buffer_and_mixed_parameter_metadata(self):
        item = weak_wrapper(hybrid())
        item.layout_model.model._parameters.append(
            MetadataTensor("cuda:1", "torch.float64", (4,))
        )
        item.layout_model.model._buffers = [
            MetadataTensor("cpu", "torch.int64", (1,)),
            MetadataTensor("cuda:0", "torch.float32", (2,)),
        ]
        event = self.record(item)
        groups = event["models"]["layout"]["tensor_groups"]
        self.assertEqual(
            {(g["kind"], g["device"], g["dtype"], g["elements"]) for g in groups},
            {
                ("parameters", "cuda:0", "torch.float32", 6),
                ("parameters", "cuda:1", "torch.float64", 4),
                ("buffers", "cpu", "torch.int64", 1),
                ("buffers", "cuda:0", "torch.float32", 2),
            },
        )
        self.assertEqual(
            event["models"]["mfr"]["tensor_groups"][0]["dtype"], "torch.float16"
        )
        self.assertEqual(
            event["models"]["ocr_detector"]["tensor_groups"][0]["dtype"],
            "torch.float16",
        )
        self.assertEqual(
            event["models"]["layout"]["weight_path"],
            "/weights/snapshots/revision/layout",
        )
        self.assertEqual(
            event["models"]["mfr"]["weight_path"], "/weights/snapshots/revision/mfr"
        )

