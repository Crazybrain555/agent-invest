    def test_missing_weights_and_empty_models_are_not_available(self):
        item = weak_wrapper(hybrid())
        del item.layout_model.model_dir
        item.mfr_model.model._parameters = []
        item.ocr_model.text_detector.net = None
        event = self.record(item)
        for name in ("layout", "mfr", "ocr_detector"):
            self.assertEqual(event["models"][name]["state"], "unavailable")
        self.assertIsNone(event["models"]["layout"]["weight_path"])
        self.assertEqual(event["models"]["mfr"]["tensor_groups"], [])
        self.assertEqual(event["models"]["ocr_recognizer"]["state"], "available")

    def test_concurrent_same_instance_only_once_distinct_instances_survive(self):
        item = weak_wrapper(hybrid())
        with ThreadPoolExecutor(max_workers=6) as executor:
            values = list(executor.map(lambda _: self.record(item), range(18)))
        self.assertEqual(sum(v is not None for v in values), 1)
        self.assertEqual(len(self.events()), 1)
        other = weak_wrapper(hybrid())
        self.assertIsNotNone(self.record(other))
        self.assertEqual(len(self.events()), 2)

    def test_instances_not_retained_by_dedup_registry(self):
        item = weak_wrapper(hybrid())
        self.record(item)
        ref = weakref.ref(item)
        del item
        gc.collect()
        self.assertIsNone(ref())

