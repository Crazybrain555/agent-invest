    def test_unexpected_metadata_failure_visible_and_retry_not_suppressed(self):
        item = weak_wrapper(hybrid())
        original = item.layout_model.model.parameters
        item.layout_model.model.parameters = lambda: (_ for _ in ()).throw(
            RuntimeError("metadata getter failure")
        )
        with self.assertRaisesRegex(RuntimeError, "metadata getter failure"):
            self.record(item)
        self.assertEqual(self.events(), [])
        item.layout_model.model.parameters = original
        self.assertIsNotNone(self.record(item))

    def test_pinned_real_sources_compile_and_hooks_follow_actual_getters(self):
        root = SERVICE / "tests/fixtures/mineru_344_preimages"
        for rel, expected in self.patcher.TARGET_PREIMAGE_SHA256.items():
            with self.subTest(path=rel):
                raw = (root / rel).read_bytes()
                self.assertEqual(hashlib.sha256(raw).hexdigest(), expected)
                patched = self.patcher.patch_source(rel, raw.decode())
                compile(patched, rel, "exec")
                if rel == "mineru/backend/hybrid/hybrid_analyze.py":
                    tree = ast.parse(patched)
                    funcs = {
                        n.name: n
                        for n in tree.body
                        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                    }
                    func = funcs["_predict_layout_for_window"]
                    statements = func.body
                    get_index = next(
                        i
                        for i, n in enumerate(statements)
                        if isinstance(n, ast.Assign)
                        and any(
                            isinstance(t, ast.Name) and t.id == "hybrid_pipeline_model"
                            for t in n.targets
                        )
                    )
                    record = statements[get_index + 1]
                    self.assertIsInstance(record, ast.Expr)
                    self.assertEqual(
                        record.value.func.id, "record_hybrid_model_devices"
                    )
                    self.assertEqual(record.value.args[0].id, "hybrid_pipeline_model")
                    orient = funcs["_apply_medium_table_orientation_labels"]
                    body = ast.unparse(orient)
                    self.assertLess(
                        body.index("get_atom_model("),
                        body.index("record_hybrid_model_devices("),
                    )
                    self.assertLess(
                        body.index("record_hybrid_model_devices("),
                        body.index("run_ocr_inference("),
                    )


